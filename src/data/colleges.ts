export const INSTITUTION_MAP = new Map(INSTITUTIONS.map((i) => [i.id, i]));
export const INSTITUTION_SLUG_MAP = new Map(INSTITUTIONS.map((i) => [i.slug, i]));

export function getInstitution(id?: string | null): Institution | undefined {
  if (!id) return undefined;
  return INSTITUTION_MAP.get(id) ?? INSTITUTION_SLUG_MAP.get(id);
}

export function institutionsByIds(ids: string[] = []): Institution[] {
  return ids.map((id) => getInstitution(id)).filter((i): i is Institution => Boolean(i));
}

/** Institutions that offer a given course. */
export function institutionsForCourse(courseId: string): Institution[] {
  return INSTITUTIONS.filter((i) => i.courseIds.includes(courseId));
}

export const INSTITUTION_TYPES = ["public", "private", "deemed", "autonomous", "government"] as const;

export function institutionsByCountry(countryId: string): Institution[] {
  return INSTITUTIONS.filter((i) => i.countryId === countryId);
}
