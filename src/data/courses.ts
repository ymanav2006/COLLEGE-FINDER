export const COURSE_MAP = new Map(COURSES.map((c) => [c.id, c]));
export const COURSE_SLUG_MAP = new Map(COURSES.map((c) => [c.slug, c]));

export function getCourse(id?: string | null): Course | undefined {
  if (!id) return undefined;
  return COURSE_MAP.get(id) ?? COURSE_SLUG_MAP.get(id);
}

export function coursesByIds(ids: string[] = []): Course[] {
  return ids.map((id) => getCourse(id)).filter((c): c is Course => Boolean(c));
}

/** Fallback label for a course id that has no record (keeps links honest). */
export function courseFallbackLabel(id: string): string {
  return id
    .split("-")
    .map((w) => (w.length <= 4 && w === w.toLowerCase() ? w.toUpperCase() : w.charAt(0).toUpperCase() + w.slice(1)))
    .join(" ");
}

