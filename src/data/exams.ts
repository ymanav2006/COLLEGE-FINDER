export const EXAM_MAP = new Map(EXAMS.map((e) => [e.id, e]));
export const EXAM_SLUG_MAP = new Map(EXAMS.map((e) => [e.slug, e]));

export function getExam(id?: string | null): EntranceExam | undefined {
  if (!id) return undefined;
  return EXAM_MAP.get(id) ?? EXAM_SLUG_MAP.get(id);
}

export function examNames(ids: string[] = []): string[] {
  return ids.map((id) => getExam(id)?.name ?? id);
}
