export const CAREER_MAP = new Map(CAREERS.map((c) => [c.id, c]));
export const CAREER_SLUG_MAP = new Map(CAREERS.map((c) => [c.slug, c]));

export function getCareer(id?: string | null): Career | undefined {
  if (!id) return undefined;
  return CAREER_MAP.get(id) ?? CAREER_SLUG_MAP.get(id);
}

export function careersByIds(ids: string[] = []): Career[] {
  return ids.map((id) => getCareer(id)).filter((c): c is Career => Boolean(c));
}

export const CAREER_DOMAINS = Array.from(new Set(CAREERS.map((c) => c.domain))).sort();
