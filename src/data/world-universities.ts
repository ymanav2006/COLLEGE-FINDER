const fee = (
  currency: string,
  annual: number,
  sourceId: string,
  hostel: number | undefined,
  other: number | undefined,
  note: string,
): TuitionInfo => ({
  currency,
  tuitionAnnual: fact(annual, sourceId, { confidence: "reported" }),
  hostelAnnual: hostel !== undefined ? fact(hostel, sourceId, { confidence: "reported" }) : undefined,
  otherFeesAnnual: other !== undefined ? fact(other, sourceId, { confidence: "reported" }) : undefined,
  estimateNote: note,
});

